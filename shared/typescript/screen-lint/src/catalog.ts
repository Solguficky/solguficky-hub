// Форма каталога экранов — данные дизайн-кода (docs/design/bot/design-code.md).
// Сами записи держит каждый бот рядом со своими экранами: каталог хаба и
// каталог бота аукциона различаются деревом, а форма у них одна.

/** Класс сообщения: от него зависит, что делает нажатие под ним. */
export type MessageClass = "screen" | "question" | "trace";

/**
 * Что обязано стоять в конце клавиатуры:
 * - `root` — меню, ряда возврата нет;
 * - `tree` — `[‹ Родитель] [Меню]`, у детей меню — `[‹ Меню]`;
 * - `confirm` — `[Да, …]` и `[Нет]` двумя рядами;
 * - `question` — режим ответа и `[Отмена]`;
 * - `choice` — выбор кнопками: `[Отмена]` последним рядом и без режима ответа;
 * - `exit` — кадр отказа: «Повторить», возврат или «Меню»;
 * - `free` — след: клавиатура принадлежит самому сообщению;
 * - `none` — клавиатуры нет вовсе.
 */
export type NavRule =
  | "root"
  | "tree"
  | "confirm"
  | "question"
  | "choice"
  | "exit"
  | "free"
  | "none";

/** Правила, нарушение которых линтер называет в `ScreenViolation.rule`. */
export type RuleName =
  | "untagged"
  | "unknown-screen"
  | "legacy-outlived"
  | "title"
  | "nav"
  | "rows"
  | "style"
  | "vocabulary"
  | "callback-data";

/**
 * Правила, которые запись может снять исключением. Предел `callback_data` и
 * цвет кнопки в список не входят: их нарушение ломает бота или подтверждение,
 * и ждать перевёрстки оно не может.
 */
export type WaivableRule = "title" | "nav" | "rows" | "vocabulary";

/** Причина исключения начинается с задачи, которая его снимет. */
export type Waiver = `PER-${number}: ${string}`;

export type ScreenEntry = {
  class: MessageClass;
  nav: NavRule;
  /** Заголовок первой строкой; нет — заголовок даёт содержимое (сходка). */
  title?: string;
  /** Родитель в дереве: запись каталога либо группа из настройки линтера. */
  parent?: string;
  /** Короткое имя для возврата с дочерних экранов: «‹ Имя». */
  backName?: string;
  /** «Обновить» разрешено: содержимое меняется без участия человека. */
  refresh?: true;
  /** Потолок рядов клавиатуры, если он строже общего. */
  maxRows?: number;
  /**
   * Экран ещё не переведён на дизайн-код. Линтер его правилами не проверяет,
   * но падает, когда такой экран уже проходит все правила: пометка не
   * переживает свою причину.
   */
  legacy?: true;
  /**
   * Именованные исключения: правило, которое экран нарушает до своей
   * перевёрстки, и задача, которая это снимет. Остальные правила проверяются.
   */
  waive?: Partial<Record<WaivableRule, Waiver>>;
};

export type Catalog = Readonly<Record<string, ScreenEntry>>;

/**
 * Ключи записей, которых нет в форме. Каталог бота объявлен `as const` без
 * `satisfies`: сборка бота не видит этого пакета. Опечатку в необязательном
 * поле ловит тест kit бота утверждением, что тип пуст.
 */
export type UnknownEntryKeys<C> = {
  [K in keyof C]: Exclude<keyof C[K], keyof ScreenEntry>;
}[keyof C];
