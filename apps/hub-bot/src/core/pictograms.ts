/** Слово со своим знаком впереди: «✔️ Да, отменить сходку». */
export function marked(sign: Pictogram, words: string): string {
  return `${sign} ${words}`;
}

/** Действие управления на экране участника: «🛠 Пульт» (PER-669). */
export function adminLabel(words: string): string {
  return marked(pictogram.admin, words);
}

