// Закрытый словарь эмодзи обоих ботов (дизайн-код, «Формат»; решение
// владельца 10 октября 2026 года). Эмодзи стоит только перед своим словом и
// только из этого словаря: подписи и строки бота берут знаки отсюда, а линтер
// экрана test kit пропускает в словах бота только их. Текст организатора —
// название, описание, рассылка, FAQ — словарём не ограничивается.

export const pictogram = {
  /** Перед «Да, …» подтверждения и перед «Допустить». */
  yes: "✔️",
  /** Перед «Нет» подтверждения и перед «Отказать». */
  no: "✖️",
  /** Перед «Убрать» и «Удалить» — кнопкой, которая ведёт к удалению. */
  remove: "🗑",
  /** Включённый переключатель уведомлений. */
  on: "🔔",
  /** Выключенный переключатель уведомлений. */
  off: "🔕",
  /** Поле «Когда:» карточки сходки. */
  when: "📅",
  /** Поле «Где:» карточки сходки. */
  where: "📍",
  /** Заголовок списка материалов на карточке сходки. */
  materials: "📎",
  /** Вход в расширения: на карточке сходки и в «Настройках» (PER-605). */
  extensions: "🧩",
  /** Поле цены карточки лота (PER-594). */
  price: "💰",
  /** Поле лидера или победителя карточки лота (PER-594). */
  leader: "👤",
  /** Поле срока торгов карточки лота (PER-594). */
  deadline: "⏳",
} as const;

export type Pictogram = (typeof pictogram)[keyof typeof pictogram];

/**
 * Начала слов, перед которыми знак разрешён: подпись или строка бота
 * начинается с «<знак> <слово>». Другого места у знака нет.
 */
export const pictogramWords: Readonly<Record<Pictogram, readonly string[]>> = {
  [pictogram.yes]: ["Да, ", "Допустить"],
  [pictogram.no]: ["Нет", "Отказать"],
  [pictogram.remove]: ["Убрать", "Удалить"],
  [pictogram.on]: ["Вкл · "],
  [pictogram.off]: ["Выкл · "],
  [pictogram.when]: ["Когда: "],
  [pictogram.where]: ["Где: "],
  [pictogram.materials]: ["Материалы:"],
  [pictogram.extensions]: ["Расширения"],
  [pictogram.price]: ["Цена: ", "Стартовая цена: ", "Цена продажи: "],
  [pictogram.leader]: ["Лидер: ", "Победитель: "],
  [pictogram.deadline]: ["Торги до: "],
};

/**
 * Заглушка пустого описания — одна у карточек сходки и лота (дизайн-код,
 * «Карточка»; PER-594).
 */
export const emptyDescription = "Описание пока не добавлено.";

/** Слово со своим знаком впереди: «✔️ Да, отменить сходку». */
export function marked(sign: Pictogram, words: string): string {
  return `${sign} ${words}`;
}

/** Начало «Да» подтверждения: «✔️ Да, <глагол и предмет>». */
export const confirmYesPrefix = marked(pictogram.yes, "Да, ");
/** «Нет» подтверждения: возврат туда, откуда подтверждение открыто. */
export const confirmNoLabel = marked(pictogram.no, "Нет");
/** Допуск по заявке и в очереди допуска. */
export const admitLabel = marked(pictogram.yes, "Допустить");
/** Отказ по заявке: ведёт на подтверждение «Да, отказать». */
export const declineLabel = marked(pictogram.no, "Отказать");
/** Вход в расширения сходки и в их настройки (ADR-064, дополнение 2026-10-12). */
export const extensionsLabel = marked(pictogram.extensions, "Расширения");

/** «✔️ Да, …» по глаголу с предметом: «отменить сходку». */
export function confirmYesLabel(action: string): string {
  return `${confirmYesPrefix}${action}`;
}
