defmodule Achievements.Rule do
  @moduledoc """
  Правило ачивки над публичными фактами модуля (ADR-077, п. 3). Правило — чистые
  функции: актор подаёт факт и состояние, правило отвечает, кому положена
  ачивка и каким стало состояние. Базу, шину и время правило не трогает.

  Правило читает только устоявшийся факт: у покупки это `invoice_paid`, а не
  `lot_sold`. Какие виды фактов оно читает, говорит `reads/0`: первый такой факт
  события фиксирует его набор, остальные факты правило не видит.

  Правилу, которому мало одного факта, сервис держит состояние: по ключам из
  `state_keys/1`, например по субъекту, — только то, что правило считает, а не
  историю фактов. Ключа нет в базе — правило получает пустую карту. Состояние
  хранится JSON-колонкой, поэтому ключи карт возвращаются строками.
  """

  alias Achievements.Fact

  @type state :: %{optional(String.t()) => term()}

  @doc "Виды доменных фактов, которые правило читает."
  @callback reads() :: [Fact.kind()]

  @doc "Ключи состояния, которые нужны правилу на этом факте."
  @callback state_keys(Fact.t()) :: [String.t()]

  @doc """
  Решение по факту: identity id тех, кому положена ачивка, и новое состояние по
  ключам. Ключ, которого нет в ответе, не меняется.
  """
  @callback evaluate(Fact.t(), %{String.t() => state()}) ::
              {[String.t()], %{String.t() => state()}}
end
