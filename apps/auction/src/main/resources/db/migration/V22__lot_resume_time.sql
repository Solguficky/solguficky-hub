-- Время возврата лота в торги финала (PER-819): экран зала пишет, сколько лот уже в торгах. Время несёт событие
-- LotResumed, а read model хранила только его номер. Колонка необязательная: NULL у строк до этой миграции значит
-- «времени нет», и страница тогда его не показывает. Перестройки нет намеренно — миграция идёт в неделю торгов, а
-- лоты, возвращённые в финал после неё, время получают; образ без колонки её не читает и не пишет.
ALTER TABLE lot_resume ADD COLUMN occurred_at timestamptz;
