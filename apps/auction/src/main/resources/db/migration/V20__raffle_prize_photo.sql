-- Фото приза розыгрыша (PER-772) байтами, по образцу lot_photo (PER-721). Строка —
-- состояние, а не журнал: какое фото у приза сейчас, решает журнал розыгрыша
-- событием со ссылкой на photo_id, а строка только держит байты под ним. Поэтому
-- ключ — пара аукциона и фото: правка, которую розыгрыш отверг после записи
-- байтов, не затирает байты фото, которое у приза уже есть.
--
-- stored_at — момент записи по часам сервиса: принятая замена и снятие удаляют
-- строки, записанные раньше них, а строку параллельной команды оставляют.
--
-- Предела размера здесь нет, как у lot_photo: его держит сервис и отвечает на
-- превышение именованным отказом.
CREATE TABLE raffle_prize_photo (
    auction_id uuid        NOT NULL,
    photo_id   uuid        NOT NULL,
    content    bytea       NOT NULL,
    media_type text        NOT NULL,
    version    text        NOT NULL,
    stored_at  timestamptz NOT NULL,
    PRIMARY KEY (auction_id, photo_id)
);
