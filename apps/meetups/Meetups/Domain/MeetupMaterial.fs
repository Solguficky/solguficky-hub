namespace Meetups.Domain

/// Вид, которым Telegram прислал файл (PER-443). Он привязан к `file_id`: фото
/// нельзя отправить документом, а документ — показать фотографией. Файл,
/// прикреплённый до появления вида, читается как `OtherFile`: его вид не записан,
/// и в карусель он не попадает.
type FileKind =
    | Photo
    | OtherFile

/// Источник материала — два вида одной моделью (RFC-002 решение 8, PER-200):
/// ссылка на сообщение Telegram хранится ссылкой, приложенный файл — `file_id`.
/// Метаданных файла сверх вида, подписи, автора оригинала и признака разрешимости здесь нет:
/// продукт их не хранит и не проверяет.
type MaterialSource =
    | MessageLink of string
    | FileId of fileId: string * kind: FileKind

/// Элемент одной упорядоченной коллекции материалов (PER-200). Место в порядке
/// назначает домен при прикреплении и дальше не пересчитывает: удаление соседей
/// позиций не двигает, поэтому остальная коллекция от него не меняется. Позиции
/// начинаются с единицы, дырки после удаления допустимы и порядок не ломают.
type MeetupMaterial =
    {
        Id: MaterialId
        Position: int
        Title: string
        Source: MaterialSource
        BoundBy: PersonId
    }
