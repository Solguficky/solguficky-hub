namespace Meetups.Domain

open System

/// Идентификатор сходки. UUIDv7 по ADR-020; канонический вид строки и версию UUID
/// проверяет граница сервиса, а не домен — собственного инварианта у значения нет.
/// Тип заведён потому, что перепутать его с идентификатором человека нельзя, а оба
/// они Guid: без раздельных типов подстановка собиралась бы молча.
type MeetupId = MeetupId of Guid

/// Идентификатор человека: автор сходки, он же выполнивший команду.
type PersonId = PersonId of Guid

/// Идентификатор материала. Отдельный тип по той же причине, что и MeetupId:
/// подстановка одного идентификатора вместо другого должна не собираться.
/// Материал генерирует вызывающая сторона, и он же служит ключом идемпотентности.
type MaterialId = MaterialId of Guid
