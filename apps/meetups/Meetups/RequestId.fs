namespace Meetups

open System

/// Сквозной идентификатор запроса (logging.md, PER-227). Значение непрозрачно:
/// его не разбирают и не сравнивают иначе как строкой. Инвариант один — непустое
/// и не длиннее предела, — и держит его `create`, потому что значение приходит
/// недоверенным заголовком, а ложится в журнал с тем же ограничением в схеме.
///
/// Тип не доменный: ни один инвариант сходки от него не зависит. Он стоит сразу
/// после домена, потому что его видят и путь записи, и граница, и воркеры.
type RequestId = private RequestId of string

[<RequireQualifiedAccess>]
module RequestId =

    /// Предел совпадает с CHECK колонки `meetup_events.request_id` (миграция 008), а
    /// проверка строже схемы — длина здесь в единицах UTF-16, пробельным считается
    /// любой символ, — поэтому значение, которое граница приняла, журнал примет тоже.
    [<Literal>]
    let MaxLength = 128

    /// `None` — «значения нет», а не отказ: вызов без заголовка допустим
    /// (integration.md), и слишком длинный заголовок трактуется так же, а не роняет
    /// команду. Выдумывать замену граница не вправе — id рождается на краю.
    let create (raw: string) : RequestId option =
        if
            String.IsNullOrWhiteSpace raw
            || raw.Length > MaxLength
        then
            None
        else
            Some(RequestId raw)

    let value (RequestId raw) = raw

    /// Собственный id цепочки, которую начинает периодическая работа Meetups:
    /// у повода по расписанию нет запроса, из которого значение могло бы прийти.
    let fresh () = RequestId(Guid.CreateVersion7().ToString())
