namespace Notifications.Reminders;

/// <summary>Настройки напоминания и его sweeper'а.</summary>
public sealed class MeetupReminderOptions
{
    public const string SectionName = "Notifications:Reminders";

    /// <summary>
    /// За сколько до начала сходки напоминать. Продуктовое значение — сутки, и
    /// оно одно: прежняя гипотеза «24 часа и 2 часа» сокращена до одного
    /// (docs/services/notifications.md). Настройкой остаётся ради тестов, где
    /// ждать сутки нечем.
    ///
    /// Смена значения не пересчитывает уже созданные задания: их <c>due_at</c>
    /// посчитан прежним упреждением и доживёт до ближайшего переноса сходки.
    /// Пересчёт не сделан намеренно — упреждение продуктовая константа, а не
    /// ручка эксплуатации, и обход всей таблицы на старте стоил бы дороже
    /// случая, которого в продукте нет.
    /// </summary>
    public TimeSpan Lead { get; set; } = TimeSpan.FromHours(24);

    /// <summary>
    /// Период прохода sweeper'а по таблице заданий.
    /// </summary>
    /// <remarks>
    /// Задаёт верхнюю границу опоздания напоминания в двух случаях: кластер
    /// лежал в момент срабатывания, и reminder не сработал. В остальное время
    /// будит грин reminder, а не этот период.
    /// </remarks>
    public TimeSpan SweepPeriod { get; set; } = TimeSpan.FromSeconds(30);

    /// <summary>Сколько заданий брать за один проход.</summary>
    /// <remarks>
    /// Предел есть, потому что первый проход после долгого простоя выбирает всё
    /// накопившееся разом. Непройденное останется живым и достанется
    /// следующему проходу — терять нечего, а неограниченная выборка держала бы
    /// транзакцию открытой тем дольше, чем хуже состояние.
    /// </remarks>
    public int SweepBatchSize { get; set; } = 256;
}
