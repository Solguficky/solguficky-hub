namespace Notifications.Reminders;

/// <summary>Настройки напоминания о счёте и его sweeper'а.</summary>
public sealed class InvoiceReminderOptions
{
    public const string SectionName = "Notifications:InvoiceReminders";

    /// <summary>
    /// Сколько после победы проходит до первого напоминания. Продуктовое
    /// значение — двенадцать часов (RFC-007, «Прочие ответы по существу»).
    /// Настройкой остаётся ради тестов, где ждать двенадцать часов нечем, и по
    /// той же причине, что у сходки: смена значения уже созданные задания не
    /// пересчитывает.
    /// </summary>
    public TimeSpan FirstLead { get; set; } = TimeSpan.FromHours(12);

    /// <summary>
    /// За сколько до срока оплаты приходит второе напоминание. Продуктовое
    /// значение — сутки, решение владельца от 21.10.2026 по развилке среза
    /// PER-330. Настройкой остаётся по той же причине, что у первого.
    /// </summary>
    public TimeSpan DueLead { get; set; } = TimeSpan.FromDays(1);

    /// <summary>
    /// Минимальный зазор между двумя напоминаниями. Срок оплаты — любое число
    /// секунд от суток до тридцати, поэтому «за сутки до срока» может совпасть
    /// с первым напоминанием или оказаться раньше него. Зазор отводит второе
    /// напоминание от первого, и два сообщения не приходят в один момент.
    /// </summary>
    public TimeSpan MinGap { get; set; } = TimeSpan.FromHours(1);
}
