namespace Notifications.Grains;

/// <summary>
/// Грин задания начала окна сниженного шага. Ключ — аукцион: задание живёт на
/// пару «аукцион и момент начала», а сообщение собирается по лотам всего
/// аукциона (ADR-047, дополнение 2026-10-12).
/// </summary>
public interface IStepWindowNotificationGrain : IGrainWithGuidKey
{
    /// <summary>
    /// Факт лота: заводит задания по окнам его реплики и будит грин к
    /// ближайшему моменту. Окна, которых у лота нет, ничего не заводят.
    /// </summary>
    Task ApplyLot(Guid lotId);

    /// <summary>
    /// Исполняет наступившие задания аукциона. Возвращает, ушло ли хоть одно
    /// сообщение: <c>false</c> — делать было нечего.
    /// </summary>
    Task<bool> FireDue();
}
