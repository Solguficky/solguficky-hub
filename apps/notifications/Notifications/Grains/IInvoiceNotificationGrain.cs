namespace Notifications.Grains;

/// <summary>
/// Грин на счёт: гранулярность «одно задание на счёт и вид», ключ —
/// идентификатор счёта.
/// </summary>
/// <remarks>
/// Отдельный грин от <see cref="ILotNotificationGrain" />, а не общий с
/// параметром субъекта: ключ у счёта свой, правило срабатывания своё, и
/// работающий путь лота это не трогает. Единственность владельца задания даёт
/// рантайм — Orleans держит одну активацию на ключ. Устойчивость лежит не
/// здесь, а в таблице <c>invoice_reminder_task</c>: грин намеренно не имеет
/// <c>[PersistentState]</c>, потому что grain storage не зарегистрирован.
///
/// Срабатывание доводится до адресных фактов <c>invoice_reminder</c> той же
/// транзакцией, что переводит задание в «сработало»; в шину их выносит общий
/// релей outbox.
/// </remarks>
public interface IInvoiceNotificationGrain : IGrainWithStringKey
{
    /// <summary>
    /// Приводит задания в соответствие с последним словом реплики о счёте:
    /// читает снимок из <c>invoice_replica</c> и заводит два задания или снимает
    /// их, если счёт оплачен.
    /// </summary>
    /// <remarks>
    /// Вход потребителя аукционных фактов: его зовут на факт выставления счёта
    /// и на факт оплаты, включая повтор, поэтому вызов обязан быть
    /// идемпотентным — и он таков, потому что решает по реплике, а не по
    /// поводу.
    /// </remarks>
    Task ApplyReplica();

    /// <summary>
    /// Исполняет задание, если его момент наступил. Возвращает <c>true</c>,
    /// если исполнил именно этот вызов.
    /// </summary>
    Task<bool> FireDue();
}
