namespace Notifications.Grains;

/// <summary>
/// Грин на лот: гранулярность «одно задание на лот» из ADR-063, ключ —
/// идентификатор лота.
/// </summary>
/// <remarks>
/// Отдельный грин от <see cref="IMeetupNotificationGrain" />, а не общий с
/// параметром субъекта: ключ у лота свой, правило срабатывания своё, и
/// работающий путь сходки это не трогает. Единственность владельца задания даёт
/// рантайм — Orleans держит одну активацию на ключ. Устойчивость лежит не
/// здесь, а в таблице <c>lot_reminder_task</c>: грин намеренно не имеет
/// <c>[PersistentState]</c>, потому что grain storage не зарегистрирован.
///
/// Срабатывание доводится до адресных фактов <c>lot_reminder</c> по следящим
/// той же транзакцией, что переводит задание в «сработало»; в шину их выносит
/// общий релей outbox.
/// </remarks>
public interface ILotNotificationGrain : IGrainWithStringKey
{
    /// <summary>
    /// Приводит задание в соответствие с последним словом реплики о лоте:
    /// читает дедлайн из <c>lot_replica</c> и отдаёт его
    /// <see cref="ApplyDeadline" />.
    /// </summary>
    /// <remarks>
    /// Вход потребителя аукционных фактов: его зовут на каждое событие лота,
    /// включая повтор, поэтому вызов обязан быть идемпотентным — и он таков,
    /// потому что решает по реплике, а не по поводу.
    /// </remarks>
    Task ApplyReplica();

    /// <summary>
    /// Приводит задание в соответствие с дедлайном лота. <c>null</c> означает,
    /// что напоминать не о чем: у лота нет торгов, он удержан для финала или
    /// пришёл в конечное положение.
    /// </summary>
    /// <remarks>
    /// Ядро решения о задании. Снаружи его зовёт <see cref="ApplyReplica" />, а
    /// напрямую — тесты, которым реплика не нужна. Транспорта у порта нет —
    /// метод грина и есть транспорт.
    /// </remarks>
    Task ApplyDeadline(DateTimeOffset? deadline);

    /// <summary>
    /// Исполняет задание, если его момент наступил. Возвращает <c>true</c>,
    /// если исполнил именно этот вызов.
    /// </summary>
    Task<bool> FireDue();
}
