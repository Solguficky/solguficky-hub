-- Пояснение автоставки видено (PER-517).
--
-- Бот показывает пояснение разницы цены и лимита на вопросе лимита, пока у
-- человека нет ни одной принятой автоставки, и ставит отметку после первой.
-- Нет строки — пояснение ещё не видено, поэтому строки появляются только у
-- тех, кто автоставку включал. Лота и суммы здесь нет: лимиты частные, и
-- сервис их не знает.
CREATE TABLE IF NOT EXISTS proxy_explainer
(
    identity_id uuid        NOT NULL,
    seen_at     timestamptz NOT NULL,

    CONSTRAINT proxy_explainer_pkey PRIMARY KEY (identity_id)
);
