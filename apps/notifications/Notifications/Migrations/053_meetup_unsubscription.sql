-- Память о явной отписке от сходки (PER-909, ADR-076, п. 5, дополнение
-- 2026-11-21). Вход в состав организаторов — создание сходки автором и
-- назначение — подписывает человека на его сходку. Отписка, сделанная самим
-- человеком, сильнее этого входа: повторный факт состава подписку не
-- возвращает, и отличить «не подписывался» от «отписался» можно только
-- строкой-памятью.
--
-- Сама подписка остаётся в meetup_subscription и по-прежнему удаляется
-- отпиской: автоподписка вставляет строку только там, где памяти нет, поэтому
-- развороты аудитории читают подписку как прежде. Ссылочной целостности с
-- чужими базами нет, как и у подписки: идентификаторы — голые uuid.

CREATE TABLE IF NOT EXISTS meetup_unsubscription
(
    identity_id     uuid        NOT NULL,
    meetup_id       uuid        NOT NULL,
    unsubscribed_at timestamptz NOT NULL,

    CONSTRAINT meetup_unsubscription_pkey PRIMARY KEY (identity_id, meetup_id)
);

COMMENT ON TABLE meetup_unsubscription IS
    'Явные отписки от сходки: строка есть — человек отписался сам, и вход в состав организаторов не подписывает его заново. Подписка живёт в meetup_subscription; явная подписка память стирает.';
