namespace AppHost.Configuration.Services;

/// <summary>
/// Часовой пояс сообщества — продуктовое значение, а не секрет, и в MVP он один:
/// сходки сообщества живут по московскому времени. Его читают три сервиса:
/// Meetups интерпретирует в нём введённый момент публикации и считает день
/// архива, бот показывает назначенный момент в карточке, Notifications
/// переводит в нём расписание в момент начала, от которого считает
/// напоминание. Значение объявлено здесь один раз, чтобы локальный прогон не
/// мог развести их пояса; production-топология назовёт своё и задаёт все три
/// переменные тем же значением.
/// </summary>
internal static class CommunityTime
{
    public const string Zone = "Europe/Moscow";
}
